// Writes each workflow README's Configuration table from its generated info.plist, so the docs list
// exactly the settings Alfred shows. Run from the repository root after `bun run build`:
//   bun scripts/readme-config.ts            update every workflow that has the markers or none yet
//   bun scripts/readme-config.ts --check    exit 1 if any README is out of date (for CI)
//   bun scripts/readme-config.ts z-wifi     only the named workflows
import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const START = "<!-- config:start (generated by scripts/readme-config.ts from info.plist; do not edit) -->";
const END = "<!-- config:end -->";
// Workflows whose Configuration section is written by hand.
const MANUAL = new Set(["z-bitwarden", "z-vscode", "z-map", "z-notion", "z-splitwise"]);
const BACK_VARS = new Set([
  "hyper_enabled",
  "hyper_control",
  "hyper_option",
  "hyper_shift",
  "hyper_command",
  "back_key",
  "back_shortcut",
]);

type Setting = {
  type: string;
  variable: string;
  label?: string;
  description?: string;
  config: { default?: unknown; pairs?: [string, string][] };
};

const cell = (text: string) => text.replace(/\|/g, "\\|").replace(/\s*\n\s*/g, " ").trim();

const defaultText = (s: Setting): string => {
  const value = s.config.default;
  if (s.type === "checkbox") return value === true || value === "1" ? "On" : "Off";
  if (s.type === "popupbutton") return s.config.pairs?.find(([, v]) => v === String(value))?.[0] ?? String(value ?? "");
  const text = String(value ?? "");
  return text ? `\`${text.replace(/`/g, "'")}\`` : "—";
};

export const table = (settings: Setting[]): string => {
  const rows: string[] = [];
  let backDone = false;
  for (const s of settings) {
    if (BACK_VARS.has(s.variable)) {
      if (!backDone)
        rows.push(
          "| Back shortcut | Hyper+B (`⌃⌥⇧⌘B`) | Hyper modifier checkboxes plus a Back key; turn Hyper off to use a custom shortcut instead. |",
        );
      backDone = true;
      continue;
    }
    rows.push(`| ${cell(s.label || s.variable)} | ${cell(defaultText(s))} | ${cell(s.description || "")} |`);
  }
  return ["| Setting | Default | What it does |", "| --- | --- | --- |", ...rows].join("\n");
};

const section = (settings: Setting[]) =>
  `${START}\nOpen the workflow in Alfred Preferences → **Configure Workflow**.\n\n${table(settings)}\n${END}`;

export const updateReadme = (readme: string, settings: Setting[]): string => {
  const block = section(settings);
  const start = readme.indexOf(START);
  if (start >= 0) {
    const end = readme.indexOf(END, start);
    if (end < 0) throw new Error("config:start without config:end");
    return readme.slice(0, start) + block + readme.slice(end + END.length);
  }
  const insert = `## Configuration\n\n${block}\n\n`;
  const before = readme.search(/^## (Development|Credits|Privacy|Credits and AI disclosure)\b/m);
  return before >= 0 ? readme.slice(0, before) + insert + readme.slice(before) : `${readme.trimEnd()}\n\n${insert.trimEnd()}\n`;
};

if (import.meta.main) {
  const args = process.argv.slice(2);
  const check = args.includes("--check");
  const only = args.filter((a) => !a.startsWith("--"));
  const names = (only.length ? only : readdirSync("workflows")).filter(
    (w) => existsSync(join("workflows", w, "package.json")) && !MANUAL.has(w),
  );
  let stale = 0;
  for (const name of names) {
    const plist = join("workflows", name, "workflow/info.plist");
    const readmePath = join("workflows", name, "README.md");
    const info = JSON.parse(execFileSync("/usr/bin/plutil", ["-convert", "json", "-o", "-", plist], { encoding: "utf8" }));
    const readme = readFileSync(readmePath, "utf8");
    const next = updateReadme(readme, info.userconfigurationconfig ?? []);
    if (next === readme) continue;
    stale++;
    if (check) console.error(`${readmePath}: Configuration section is out of date`);
    else writeFileSync(readmePath, next);
  }
  if (check && stale) process.exit(1);
  console.log(check ? "README configuration up to date" : `Updated ${stale} README(s)`);
}
