import { spawn } from "node:child_process";
import { bool } from "./env.ts";
import { JXA_STDIN, jxa, publicEnv } from "./proc.ts";

/**
 * Secrets are written with the nspasteboard.org markers, so Alfred's clipboard history,
 * Maccy, Paste and friends skip them. Plain `pbcopy` can't set these types.
 */
const copyScript = `${JXA_STDIN}
ObjC.import("AppKit");
const pb = $.NSPasteboard.generalPasteboard;
pb.clearContents;
pb.setStringForType(stdin(), "public.utf8-plain-text");
pb.setStringForType("", "org.nspasteboard.ConcealedType");
pb.setStringForType("", "org.nspasteboard.TransientType");
pb.setStringForType("", "org.nspasteboard.AutoGeneratedType");
String(pb.changeCount);`;

const changeCountScript = `ObjC.import("AppKit"); String($.NSPasteboard.generalPasteboard.changeCount);`;
const clearScript = `ObjC.import("AppKit"); $.NSPasteboard.generalPasteboard.clearContents; "";`;

/** Copy a secret; returns the pasteboard change count so a later clear only wipes our value. */
export const copySecret = async (value: string): Promise<number> => Number(await jxa(copyScript, value));

/** Plain copy (non-secret things like a Send link). */
export const copyText = async (value: string): Promise<void> => {
  await new Promise<void>((resolve) => {
    const child = spawn("/usr/bin/pbcopy", [], { env: publicEnv() });
    child.on("close", () => resolve());
    child.stdin.end(value);
  });
};

export const changeCount = async (): Promise<number> => Number(await jxa(changeCountScript));

/** Clear only if nothing new was copied since (so we never wipe the user's own copy). */
export const clearIfUnchanged = async (expected: number): Promise<boolean> =>
  (await changeCount()) === expected ? (await jxa(clearScript), true) : false;

/**
 * Detach a tiny process that waits and clears. It re-runs this bundle with `clear-after`,
 * so the secret itself is never passed along — only the change count.
 */
export const scheduleClear = (expected: number, seconds: number): void => {
  if (seconds <= 0) return;
  const child = spawn(
    process.execPath,
    [process.argv[1] ?? "", "clear-after", String(seconds), String(expected)],
    {
      detached: true,
      stdio: "ignore",
      env: publicEnv(),
    },
  );
  child.unref();
};

/** Setting "Never put passwords on the clipboard": autofill/paste type them instead. */
export const passwordsOffClipboard = (): boolean => bool("no_clipboard");
